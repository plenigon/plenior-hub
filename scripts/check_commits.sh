#!/usr/bin/env bash
set -uo pipefail

if [ $# -ge 1 ]; then
    base="$1"
else
    if git rev-parse --verify --quiet origin/main >/dev/null; then
        if ! base="$(git merge-base HEAD origin/main 2>/dev/null)"; then
            echo "check_commits: cannot resolve base" >&2
            exit 2
        fi
    else
        # Before the first push there is no origin/main: check every commit.
        base=""
    fi
fi

if [ -n "$base" ]; then
    range="$base..HEAD"
else
    range="HEAD"
fi

if ! commits="$(git rev-list --no-merges "$range" 2>/dev/null)"; then
    echo "check_commits: cannot resolve base" >&2
    exit 2
fi
if [ -z "$commits" ]; then
    exit 0
fi

failed=0
dependabot='dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>'
pattern='^(feat|fix|refactor|test|docs|chore|build|ci|perf|revert)(\([a-z0-9._/-]+\))?!?: [^ ]'

while IFS= read -r sha; do
    if [ -z "$sha" ]; then
        continue
    fi
    subject="$(git log -1 --format=%s "$sha")"
    case "$subject" in
        'Revert "'*|'fixup! '*|'squash! '*|'amend! '*)
            continue
            ;;
    esac

    reasons=""

    if [[ ! "$subject" =~ $pattern ]]; then
        reasons="non-conventional subject"
    fi

    if [ "${#subject}" -gt 72 ]; then
        if [ -n "$reasons" ]; then
            reasons="$reasons, subject too long"
        else
            reasons="subject too long"
        fi
    fi

    body="$(git log -1 --format=%B "$sha" | tail -n +2)"
    has_ai=0
    if printf '%s\n' "$body" | grep -iqE '^(Co-authored-by|Signed-off-by):.*(codex|openai|chatgpt|claude|anthropic|copilot|gemini|grok|xai|muse|meta)'; then
        has_ai=1
    fi
    if printf '%s\n' "$body" | grep -qF 'Generated with'; then
        has_ai=1
    fi
    if printf '%s\n' "$body" | grep -qF 'Generated by'; then
        has_ai=1
    fi
    if [ "$has_ai" -eq 1 ]; then
        if [ -n "$reasons" ]; then
            reasons="$reasons, AI trailer"
        else
            reasons="AI trailer"
        fi
    fi

    author="$(git log -1 --format='%an <%ae>' "$sha")"
    # Dependabot signs off with a different address than it authors with.
    if [ "$author" != "$dependabot" ] &&
        ! printf '%s\n' "$body" | grep -qxF "Signed-off-by: $author"; then
        if [ -n "$reasons" ]; then
            reasons="$reasons, missing sign-off"
        else
            reasons="missing sign-off"
        fi
    fi

    if [ -n "$reasons" ]; then
        short="$(git rev-parse --short "$sha")"
        printf '%s %s: %s\n' "$short" "$reasons" "$subject"
        failed=1
    fi
done <<EOF
$commits
EOF

exit "$failed"
